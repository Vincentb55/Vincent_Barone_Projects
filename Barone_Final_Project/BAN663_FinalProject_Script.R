#revenue data with artist type and country all in the same plot, so they want to automatically summarize
# key metrics for each type
#
# What parameter makes it reusable: Artist_Type makes it resonable due to the various
# options
#

my_analysis_function <- function(data, artist_type) {

  # Input validation
  if (!is.character(artist_type))
    stop("Artist_Type_During_Album must be a character string.")

  valid <- unique(data$Artist_Type_During_Album)
  if (!artist_type %in% valid)
    stop(paste("Not found:", artist_type,
               "\nValid options:", paste(valid, collapse = ", ")))

  # Analysis logic — replace with your actual task
  result <- data %>%
    filter(Artist_Type_During_Album == artist_type) %>%
    summarize(
      artist_type       = artist_type,
      number_of_albums  = n(),
      avg_total_revenue = round(mean(Total_Album_Revenue, na.rm = TRUE), 2),
      avg_album_budget  = round(mean(Album_Budget,        na.rm = TRUE), 2),
      avg_mkt_budget    = round(mean(Marketing_Budget,    na.rm = TRUE), 2),
      avg_profit        = round(mean(Total_Album_Revenue - Album_Budget - Marketing_Budget, na.rm = TRUE), 2),
      .groups     = "drop"
    )

  return(result)
}



